#' Non-linear fits of different models to the decomposition trajectory
#' of one cohort (as in typical litterbag studies) data.
#' Models range from very simple (and easy to fit with limited data)
#' to more complex.
#'
#' @title Fit different models to single cohort decomposition data
#'
#' @param time time since decomposition began, that is, ti-t0
#'
#' @param  mass.remaining proportional mass remaining, that is, mi/m0. Values above 1 (apparent
#'   mass gain, up to 2) or slightly below 0 (down to -0.1) are kept and treated as measurement
#'   error, with an informative warning (see Details).
#'
#' @param model there are six models currently implemented (see below); defaults to \code{"neg.exp"}
#'
#' @param iters Number of random starts for the fitting.  Use higher numbers for models with larger numbers of parameters and for models that inherently tend to be less identifiable.
#'
#' @param upper,lower \bold{Optional} user specified values for the upper and lower bounds used by
#' \code{optim} in the fitting procedure. Use with care, only minimal sanity checking is currently
#'  implemented.
#'
#' @param quiet if \code{TRUE}, suppress the message reporting the number of successful fits
#'
#' @param ...  Additional arguments passed to \code{\link{optim}}
#'
#' @return returns a litfit object with the following elements:
#'  \itemize{
#' \item{\bold{optimFit:} a list generated by the \code{\link{optim}} function}
#' \item{\bold{logLik:} the log-likelihood of the model}
#' \item{\bold{time:} vector of time (same as input)}
#' \item{\bold{mass:} vector of mass remaining (same as input)}
#' \item{\bold{predicted:} predicted values from the model for each of the points within time}
#' \item{\bold{model:} name of the model }
#' \item{\bold{nparams:} number of fit parameters in the model}
#' \item{\bold{AIC:} AIC of the model fit}
#' \item{\bold{AICc:} AICc of the model fit}
#' \item{\bold{BIC:} BIC of the model fit}
#' \item{and some other potentially useful things}
#' }
#'
#' @import stats
#' @export
#'
#' @details the model likelihood is maximized using methods available in \code{\link[stats]{optim}}.  Optimization methods to be used within optim can be specified through the control object (i.e., control$method).  The default method is L-BFGS-B with bounds specific to each model. Each model
#' \itemize{
#' \item{\bold{neg.exp} The classic negative exponential model--one parameter (Olson 1963)}
#' \item{\bold{weibull} The Weibull residence time model--two parameters (Frechet 1927)}
#' \item{\bold{discrete.parallel} Two pools in parallel with a term for the fraction of initial mass in each pool--three parameter (Manzoni et al. 2012)}
#' \item{\bold{discrete.series} A three parameter model in which there is the possibility of two sequential pools (Manzoni et al. 2012)}
#' \item{\bold{cont.quality} (Ågren and Bosatta 1996, see also Manzoni et al. 2012)}
#' \item{\bold{neg.exp.limit} A negative exponential decaying towards a non-zero asymptote (\eqn{A e^{-kt} + B})--three parameters}
#' }
#' \emph{Warning}: difficulty in finding the optimal solution is determined by an interaction between the nature and complexity of the
#' likelihood space (which is both data- and model-dependent) as well as the optimization methods.  There can never be a guarantee that the optimal solution is found, but using many random starting points will increase these odds.  It should be noted that there is significant variation among models in identifiability, with some models inherently less identifiable likely due to a tendency to form for flat ridges in likelihood space.  The confidence in the fit should be very low in these cases (see Cornwell and Weedon 2013).   A number of random starting points are used in optimization and are given through the iters.  The function checks whether the best 5 optimizations have converged on the same likelihood, and if they have not this function will return a warning.
#'
#' \emph{Values outside 0--1}: measurement error, especially early in decomposition or when
#' decomposition is slow, can produce proportional mass remaining values slightly above 1
#' (i.e. negative mass loss). These values are kept in the fit, since removing or truncating
#' them would bias the estimates, but \code{fit_litter} warns (class
#' \code{litterfitter_mass_above_one}). If the data also show little overall mass loss, the
#' warning notes that parameters may be poorly constrained and that derived quantities such as
#' \code{\link{time_to_prop_mass_remaining}} and \code{\link{steady_state}} are extrapolations.
#' Slightly negative values (down to -0.1) are similarly kept with a warning (class
#' \code{litterfitter_mass_below_zero}). Use \code{suppressWarnings(..., classes = ...)} to
#' silence these once checked.
#'
#' @author Will Cornwell and James Weedon
#'
#' @references \itemize{ \item{Ågren, G. and Bosatta, E. (1996) Quality: a bridge between theory and experiment in soil organic matter studies. Oikos, 76, 522–528.}
#' \item{Cornwell, W. K., and J. T. Weedon. (2013).  Decomposition trajectories of diverse litter types: a model selection analysis. Methods in Ecology and Evolution.}
#' \item{Frechet, M. (1927) Sur la loi de probabilite de lecart maximum. Ann de la Soc polonaise de Math, 6, 93–116.}
#' \item{Manzoni, S., Pineiro, G., Jackson, R. B., Jobbagy, E. G., Kim, J. H., & Porporato, A. (2012). Analytical models of soil and litter decomposition: Solutions for mass loss and time-dependent decay rates. Soil Biology and Biochemistry, 50, 66-76.}
#' \item{Olson, J.S. (1963) Energy storage and the balance of producers and decomposers in ecological systems. Ecology, 44, 322–331.}}
#'
#' @seealso \code{\link{optim}},
#' \code{\link{steady_state}},
#' \code{\link{plot.litfit}}
#'
#' @examples
#' data(pineneedles)
#' fit <- fit_litter(
#'   time = pineneedles$Year, mass.remaining = pineneedles$Mass.remaining,
#'   model = "neg.exp", iters = 1000
#' )
fit_litter <- function(
  time, mass.remaining, model = c(
    "neg.exp", "weibull", "discrete.parallel",
    "discrete.series", "cont.quality", "neg.exp.limit"
  ), iters = 500,
  upper = NULL, lower = NULL, quiet = FALSE, ...
) {
  model <- match.arg(model)

  if (length(time) != length(mass.remaining)) {
    stop("Time vector must have the same length and correspond to the mass remaining vector")
  }
  if (!is.numeric(time) || !is.numeric(mass.remaining)) {
    stop("time and mass.remaining must be numeric vectors")
  }

  if (!is.numeric(iters) || length(iters) != 1 || is.na(iters) || iters < 1) {
    stop("iters must be a single positive number")
  }

  missing_obs <- is.na(time) | is.na(mass.remaining)
  if (any(missing_obs)) {
    warning(warningCondition(
      paste(sum(missing_obs), "observation(s) with missing time or mass removed"),
      class = "litterfitter_missing_removed"
    ))
    time <- time[!missing_obs]
    mass.remaining <- mass.remaining[!missing_obs]
  }

  nparams_model <- length(model_param_names(model))
  # Every curve except neg.exp.limit is pinned at mass 1 at time 0, so
  # harvests at as many distinct positive times as there are parameters
  # identify the fit, e.g. a single harvest for neg.exp.
  pinned_at_origin <- model != "neg.exp.limit"
  identified_from_origin <- pinned_at_origin &&
    length(unique(time[time > 0])) >= nparams_model
  if (length(time) <= nparams_model && !identified_from_origin) {
    stop(paste(
      "Too few observations to fit model", model, "- need more than",
      nparams_model, "data points"
    ))
  }

  if (any(!is.finite(time)) || any(!is.finite(mass.remaining))) {
    stop("time and mass.remaining must not contain infinite values")
  }

  if (min(time) < 0) {
    stop("Check time vector; negative values detected.")
  }
  if (length(unique(time)) < 2 && !identified_from_origin) {
    stop("Need observations at two or more distinct time points")
  }
  if (length(time) <= nparams_model || length(unique(time)) < 2) {
    warn_once_origin_only(model, length(unique(time[time > 0])))
  }

  if (any(mass.remaining < -0.1) || max(mass.remaining) > 2) {
    stop("Check mass remaining vector; must be in proportional mass remaining (between 0 and ~1).")
  }
  check_mass_range(mass.remaining)

  # test that if user supplied bounds, there are enough of them
  default_upper <- model_bounds(model, "upper")
  default_lower <- model_bounds(model, "lower")
  if (!is.null(upper) && length(upper) != length(default_upper)) {
    stop(paste("Incorrect number of upper bounds supplied, should be:", length(default_upper)))
  }
  if (!is.null(lower) && length(lower) != length(default_lower)) {
    stop(paste("Incorrect number of lower bounds supplied, should be:", length(default_lower)))
  }
  test.upper <- if (is.null(upper)) default_upper else upper
  test.lower <- if (is.null(lower)) default_lower else lower
  if (any(test.lower >= test.upper)) {
    stop("Each lower bound must be smaller than the corresponding upper bound")
  }

  fit <- multioptimFit(time, mass.remaining, model,
    iters = as.integer(iters), upper = upper,
    lower = lower, quiet = quiet, ...
  )
  names(fit$par) <- model_param_names(model)

  predicted_vals <- do.call(model, c(list(time), as.list(fit$par)))
  LL <- calculateLL(predicted_vals, mass.remaining, sqrt(fit$value / length(time)))
  nps <- length(fit$par)
  model.AIC <- calculateAIC(LL, nps)
  model.AICc <- calculateAICc(LL, nps, length(mass.remaining))
  model.BIC <- calculateBIC(LL, nps, length(mass.remaining))
  fit.out <- list(
    optimFit = fit, logLik = LL, fitAIC = model.AIC, fitAICc = model.AICc,
    fitBIC = model.BIC, time = time, mass = mass.remaining, predicted = predicted_vals,
    model = model, nparams = nps
  )
  class(fit.out) <- "litfit"

  # test if best fits are on boundary values
  on_bound <- fit.out$optimFit$par == test.lower | fit.out$optimFit$par == test.upper
  if (any(on_bound)) {
    msg <- paste0(
      "one or more parameters fit on the boundary (",
      paste(names(fit.out$optimFit$par)[on_bound], collapse = ", "),
      "), check fit closely"
    )
    if (is.null(upper) && is.null(lower) && max(time) > 20) {
      msg <- paste0(
        msg, ". The default bounds assume time is measured in years; ",
        "if time is in days or months, convert it to years or supply 'upper' and 'lower'."
      )
    }
    warning(msg)
  }
  return(fit.out)
}
